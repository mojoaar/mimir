import QRCode from 'qrcode'
import { beginEnrollment, pendingEnrollment } from '@/lib/auth/mfa'
import { translator } from '@/lib/i18n/request'
import { ConfirmForm } from './mfa-form'

/**
 * The QR plus the confirm field. Lives in its own file so the app layout can
 * gate every page with it when the install requires two-factor.
 */
export async function Enrolment({ userId }: { userId: string }) {
  const t = await translator()
  const enrollment = (await pendingEnrollment(userId)) ?? (await beginEnrollment(userId))
  const svg = await QRCode.toString(enrollment.uri, { type: 'svg', margin: 1 })

  return (
    <div className="flex flex-col gap-4 rounded-lg border border-[var(--border)] p-4">
      <p className="text-sm">{t('app.mfa.scan')}</p>
      <div
        className="w-48 rounded-md bg-[#ffffff] p-2 [&_svg]:h-full [&_svg]:w-full"
        // Generated by the QR encoder from our own secret, never user input.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <p className="text-xs text-[var(--text-muted)]">
        {t('app.mfa.manual')} <code className="break-all">{enrollment.secret}</code>
      </p>
      <ConfirmForm
        labels={{
          codeLabel: t('app.mfa.codeLabel'),
          checking: t('app.mfa.checking'),
          turnOn: t('app.mfa.turnOn'),
        }}
      />
    </div>
  )
}
